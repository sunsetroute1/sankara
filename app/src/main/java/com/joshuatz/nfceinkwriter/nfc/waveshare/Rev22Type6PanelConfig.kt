    fun apply(link: Rev22Link, transceive: (Rev22Link, ByteArray, String) -> Unit) {
        PRE_COMMANDS.forEachIndexed { i, cmd ->
            transceive(link, cmd, "type6-pre#$i")
        }

        // Official r() reuses one 257-byte 74 9A frame; later steps only patch [4] and a short n[] slice.
        val templateFrame = newTemplateFrame()
        patchTemplateFrame(templateFrame, 0x99, 0, 153)
        transceive(link, templateFrame, "type6-template-init")
        Thread.sleep(100)

        transceive(link, bytes(0x74, 0x99, 0x00, 0x0D, 0x01, 0x3F), "type6-pre writeReg 0x3f")
        patchTemplateFrame(templateFrame, 1, 153, 1)
        transceive(link, templateFrame, "type6-template-a")
        transceive(link, bytes(0x74, 0x99, 0x00, 0x0D, 0x01, 0x03), "type6-pre writeReg 0x03")
        patchTemplateFrame(templateFrame, 1, 154, 1)
        transceive(link, templateFrame, "type6-template-b")
        transceive(link, bytes(0x74, 0x99, 0x00, 0x0D, 0x01, 0x04), "type6-pre writeReg 0x04")
        patchTemplateFrame(templateFrame, 3, 155, 3)
        transceive(link, templateFrame, "type6-template-c")
        transceive(link, bytes(0x74, 0x99, 0x00, 0x0D, 0x01, 0x2C), "type6-pre writeReg 0x2c")
        patchTemplateFrame(templateFrame, 1, 158, 1)
        transceive(link, templateFrame, "type6-template-d")

        POST_COMMANDS.forEachIndexed { i, cmd ->
            transceive(link, cmd, "type6-post#$i")
        }
    }

    private fun newTemplateFrame(): ByteArray =
        ByteArray(257).also {
            it[0] = 0x74
            it[1] = 0x9A.toByte()
            it[2] = 0x00
            it[3] = 0x0E
        }

    private fun patchTemplateFrame(frame: ByteArray, index4: Int, templateOffset: Int, templateLen: Int) {
        frame[4] = index4.toByte()
        System.arraycopy(TEMPLATE_N, templateOffset, frame, 5, templateLen)
    }

    private fun bytes(vararg values: Int): ByteArray =
        ByteArray(values.size) { values[it].toByte() }
