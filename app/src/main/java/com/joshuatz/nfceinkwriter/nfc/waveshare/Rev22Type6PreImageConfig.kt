package com.joshuatz.nfceinkwriter.nfc.waveshare

/**
 * Official NFCTag [activity.a.r] type-6 pre-image block (labels 0bce..0f1a).
 * Runs after panel init and immediately before writeReg(0x24) + image transfer.
 */
internal object Rev22Type6PreImageConfig {

    private val COMMANDS = listOf(
        bytes(0x74, 0x99, 0x00, 0x0D, 0x01, 0x21),
        bytes(0x74, 0x9A, 0x00, 0x0E, 0x02, 0x88, 0x80),
        bytes(0x74, 0x99, 0x00, 0x0D, 0x01, 0x18),
        bytes(0x74, 0x9A, 0x00, 0x0E, 0x01, 0x80),
        bytes(0x74, 0x99, 0x00, 0x0D, 0x01, 0x22),
        bytes(0x74, 0x9A, 0x00, 0x0E, 0x01, 0xB1),
        bytes(0x74, 0x99, 0x00, 0x0D, 0x01, 0x20),
        bytes(0x74, 0x99, 0x00, 0x0D, 0x01, 0x1A),
        bytes(0x74, 0x9A, 0x00, 0x0E, 0x02, 0x5A, 0x00),
        bytes(0x74, 0x99, 0x00, 0x0D, 0x01, 0x22),
        bytes(0x74, 0x9A, 0x00, 0x0E, 0x01, 0x91),
        bytes(0x74, 0x99, 0x00, 0x0D, 0x01, 0x20),
        bytes(0x74, 0x99, 0x00, 0x0D, 0x01, 0x01),
        bytes(0x74, 0x9A, 0x00, 0x0E, 0x03, 0x27, 0x01, 0x00),
        bytes(0x74, 0x99, 0x00, 0x0D, 0x01, 0x11),
        bytes(0x74, 0x9A, 0x00, 0x0E, 0x01, 0x03),
        bytes(0x74, 0x99, 0x00, 0x0D, 0x01, 0x44),
        bytes(0x74, 0x9A, 0x00, 0x0E, 0x02, 0x00, 0x0F),
        bytes(0x74, 0x99, 0x00, 0x0D, 0x01, 0x45),
        bytes(0x74, 0x9A, 0x00, 0x0E, 0x04, 0x00, 0x00, 0x27, 0x01),
        bytes(0x74, 0x99, 0x00, 0x0D, 0x01, 0x4E),
        bytes(0x74, 0x9A, 0x00, 0x0E, 0x01, 0x00),
        bytes(0x74, 0x99, 0x00, 0x0D, 0x01, 0x4F),
        bytes(0x74, 0x9A, 0x00, 0x0E, 0x02, 0x00, 0x00),
    )

    fun apply(link: Rev22Link, transceive: (Rev22Link, ByteArray, String) -> Unit) {
        COMMANDS.forEachIndexed { i, cmd ->
            transceive(link, cmd, "type6-preImage#$i")
        }
    }

    private fun bytes(vararg values: Int): ByteArray =
        ByteArray(values.size) { values[it].toByte() }
}
